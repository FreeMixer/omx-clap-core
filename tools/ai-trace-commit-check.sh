# ai-trace-commit-check.sh: fail when a commit message carries an AI-attribution line.
#
#   ai-trace-commit-check.sh <range>          every commit in the range (e.g. origin/main..HEAD)
#   ai-trace-commit-check.sh --msg-file FILE  one message (the commit-msg hook; # lines are git comments, skipped)
#   ai-trace-commit-check.sh --text-file FILE any text, every line judged (PR titles and bodies)
#   ai-trace-commit-check.sh --selftest       fixtures plus a sabotage run
#
# Exit 0 clean, 1 a hit (each commit and offending line is named), 2 a range, file or pattern list that cannot be read
# (any crash is 2). Callers refuse on 2: a checker that cannot judge is never a pass.
# The patterns are ai-trace-patterns.json beside this script, the same list ai-trace-sweep.sh strips
# issue and PR text with, and the one list every door reads: merge-pr.sh, integrate-check.sh, pr-from-devel.sh
# (ops/tools/tests/ai-trace-one-list.t.sh refuses a second list). AI_TRACE_PATTERNS names another JSON (self-tests). Repos that cannot see the ops tree carry a copy of both files.
set -euo pipefail
export AI_TRACE_SELF="${BASH_SOURCE[0]}"
exec python3 -I - "$@" <<'PY'
import json, os, re, subprocess, sys

here = os.path.dirname(os.path.realpath(os.environ["AI_TRACE_SELF"]))
pfile = os.environ.get("AI_TRACE_PATTERNS") or os.path.join(here, "ai-trace-patterns.json")


def load():
    with open(pfile, encoding="utf-8") as f:
        return [(m["name"], re.compile(m["pattern"], re.I | re.M)) for m in json.load(f)["markers"]]


def hits(text, markers):
    out = []
    for n, line in enumerate(text.splitlines(), 1):
        for name, rx in markers:
            if rx.search(line):
                out.append((n, name, line.strip()))
    return out


def report(label, text, markers):
    h = hits(text, markers)
    for n, name, line in h:
        print(f"{label}: line {n} [{name}]: {line}")
    return len(h)


def git(*a):
    p = subprocess.run(["git", *a], capture_output=True, text=True)
    if p.returncode:
        print(f"ai-trace-commit-check: git {' '.join(a[:3])}: {p.stderr.strip()}", file=sys.stderr)
        sys.exit(2)
    return p.stdout


def selftest():
    # every marker is joined from fragments, so this file carries none of the lines it must refuse
    CL, cl, AN, OP, CP, GEN = "Cl" + "aude", "cl" + "aude", "anthr" + "opic", "Op" + "us", "Copi" + "lot", "Gener" + "ated"
    fx = {
        "co-authored-by": f"Fix x\n\nCo-Authored-By: {CL} {OP} <noreply@{AN}.com>\n",
        "session-trailer": f"Fix x\n\n{CL}-Session: https://{cl}.ai/code/session_01\n",
        "generated-footer": f"Fix x\n\n\U0001F916 {GEN} with [{CL} Code](https://{cl}.com/{cl}-code)\n",
        "session-url": f"Fix x\n\nsee https://{cl}.ai/code/session_9\n",
        # the shapes the omx-dsp#155 review saw pass
        "assisted-by": f"Fix x\n\nAssisted-by: {CL}\n",
        "made-with": f"Fix x\n\nMade with {CL} Code\n",
        "generated-with-claude": f"Fix x\n\n{GEN} with {CL}\n",
        "generated-by-trailer": f"Fix x\n\nGenerated-by: {CL}\n",
        "co-author-model": f"Fix x\n\nCo-authored-by: {OP} 5.5 <x@example.invalid>\n",
        "co-author-github-copilot": f"Fix x\n\nCo-authored-by: GitHub {CP} <{CP.lower()}@github.com>\n",
    }
    clean = ("Fix x\n\nGenerated by the build; mentions .claude/ and a Co-Authored-By: Pau line.\n"
             "Assisted-by: Pau Aliagas\nMade with care; generated with tools/rules-index-gen.sh\n"
             f"A review quoted 'Assisted-by: {CL}' and 'Co-authored-by: {OP} 5.5 <x>' as shapes that passed.\n")
    def run(markers):
        bad = [k for k, v in fx.items() if not hits(v, markers)]
        if hits(clean, markers):
            bad.append("clean-flagged")
        return bad
    m = load()
    first = run(m)
    print("selftest:", "GREEN" if not first else f"RED {first}")
    sab = run([x for x in m if x[0] not in ("co-authored-by", "ai-co-author", "anthropic-noreply", "session-trailer")])
    print("sabotage (the co-author, email and session patterns removed):", "RED as expected" if sab else "still GREEN: blind")
    # each #152 shape is seen by a pattern of its own family, not by luck
    new = ["assisted-by", "made-with", "generated-with-claude", "generated-by-trailer", "co-author-model", "co-author-github-copilot"]
    sab2 = run([x for x in m if x[0] not in ("ai-assisted-by", "generated-footer", "ai-co-author-model")])
    blind = [k for k in new if k not in sab2]
    print("sabotage (the assisted-by, generated and model co-author patterns removed):",
          "RED as expected" if not blind else f"still GREEN for {blind}: blind")
    return 0 if not first and sab and not blind else 1


def main(a):
    if a == ["--selftest"]:
        return selftest()
    markers = load()
    if len(a) == 2 and a[0] == "--msg-file":
        try:
            text = open(a[1], encoding="utf-8", errors="replace").read()
        except OSError as e:
            print(f"ai-trace-commit-check: {e}", file=sys.stderr)
            return 2
        # lines git adds as comments are not part of the message
        text = "\n".join(l for l in text.splitlines() if not l.startswith("#"))
        return 1 if report("commit message", text, markers) else 0
    if len(a) == 2 and a[0] == "--text-file":
        try:
            text = open(a[1], encoding="utf-8", errors="replace").read()
        except OSError as e:
            print(f"ai-trace-commit-check: {e}", file=sys.stderr)
            return 2
        return 1 if report("text", text, markers) else 0
    if len(a) == 1 and not a[0].startswith("-"):
        shas = git("rev-list", a[0]).split()
        bad = 0
        for sha in shas:
            bad += report(sha[:12], git("log", "-1", "--format=%B", sha), markers)
        print(f"ai-trace-commit-check: {len(shas)} commits, {bad} offending lines")
        return 1 if bad else 0
    print(__doc__ if False else "usage: ai-trace-commit-check.sh <range> | --msg-file FILE | --text-file FILE | --selftest", file=sys.stderr)
    return 2


try:
    rc = main(sys.argv[1:])
except Exception as e:  # a bad or missing pattern file, a decode error: unreadable, never "a hit"
    print(f"ai-trace-commit-check: {type(e).__name__}: {e}", file=sys.stderr)
    rc = 2
sys.exit(rc)
PY
